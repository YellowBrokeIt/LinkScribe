"""Real speech-recognition integration smoke for GitHub Actions.

Synthesized media is generated by espeak-ng in CI. No real YouTube media, user
recordings, model credentials, or external local hardware are required.
"""
from __future__ import annotations

import os
import tempfile
import time
from pathlib import Path
from fastapi.testclient import TestClient
import app
import library


def main() -> None:
    sample = Path(os.environ.get('LINKSCRIBE_QA_AUDIO', '/tmp/linkscr-qa-voice.wav'))
    assert sample.is_file() and sample.stat().st_size > 250, 'Missing generated spoken WAV'
    with tempfile.TemporaryDirectory(prefix='linkscr-qa-real-audio-') as root:
        base = Path(root)
        app.DATA_DIR = base / 'jobs'
        library.DB_FILE = base / 'library.sqlite3'
        # Real PyAV duration parser (no mocking).
        app._check_uploaded_duration(sample)
        with TestClient(app.app) as client, sample.open('rb') as fp:
            response=client.post('/api/upload',files={'file':('spoken.wav',fp,'audio/wav')},data={
                'consent':'true','model':'tiny','language':'en'})
            assert response.status_code==200, response.text
            job_id=response.json()['id']
            deadline=time.monotonic()+240
            while time.monotonic()<deadline:
                current=client.get(f'/api/jobs/{job_id}').json()
                if current['status'] in ('done','error'): break
                time.sleep(1)
            else:
                raise AssertionError('Real Whisper transcription timed out after 240 seconds')
            assert current['status']=='done',current
            transcript=client.get(f'/api/library/{job_id}').json()
            segments=transcript['segments']
            assert len(segments)>=1 and all(item.get('text') for item in segments)
            text=client.get(f'/api/library/{job_id}/download/txt').text
            assert len(text.strip())>=8, text
            assert client.get(f'/api/library/{job_id}/download/srt').status_code==200
            assert client.get(f'/api/library/{job_id}/download/vtt').status_code==200
            assert client.get(f'/api/library/{job_id}/download/zip').status_code==200
            assert not list(app.jobs[job_id].workdir.glob('input.*')), 'Uploaded audio was not cleaned'
            print('REAL END-TO-END INPUT FILE -> PyAV -> Whisper tiny -> SQLite -> exports: PASS')
            print('Detected language:',transcript['language'])
            print('Transcript sample:',text[:300])


if __name__=='__main__':
    main()
